update public.rch_mappings m set ingredient_id=s.id from (
 select m.rch_id, (array_agg(i.id))[1] as id
 from public.rch_mappings m join public.ingredients i on lower(trim(i.name))=lower(trim(m.name))
 join public.units u on u.id=i.unit_id
 where i.active and not m.excluded and ((m.unit_code=1 and u.code in ('g','kg')) or (m.unit_code=3 and u.code in ('ml','l')) or (m.unit_code=4 and u.code='pz'))
 group by m.rch_id having count(*)=1
) s where m.rch_id=s.rch_id;
