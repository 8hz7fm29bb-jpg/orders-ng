create table public.rch_mappings (
 rch_id bigint primary key check(rch_id>0), name text not null,
 unit_code integer not null check(unit_code in (1,3,4)),
 ingredient_id uuid references public.ingredients(id) on delete set null,
 excluded boolean not null default false
);
create index rch_mappings_ingredient_idx on public.rch_mappings(ingredient_id);
create table public.rch_imports (
 id uuid primary key default gen_random_uuid(),filename text not null,
 period_from date not null,period_to date not null check(period_to>=period_from),
 file_hash text not null unique,rows jsonb not null check(jsonb_typeof(rows)='array'),
 mappings jsonb not null check(jsonb_typeof(mappings)='array'),
 created_at timestamptz not null default now(),
 exclude using gist (daterange(period_from,period_to,'[]') with &&)
);
alter table public.rch_mappings enable row level security;
alter table public.rch_imports enable row level security;
revoke all on public.rch_mappings,public.rch_imports from anon,authenticated;
grant select,insert,update,delete on public.rch_mappings,public.rch_imports to authenticated;
